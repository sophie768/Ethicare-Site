#!/usr/bin/env node
// =============================================================================
// Ethicare Resourcing — rebuild the guide list inside /request-a-guide
//
// The page keeps its URL because 659 pages and any number of shared links point
// at it. What changed is what it offers: we are not printing the guides, so it
// now hands over the PDF instead of taking an order for a book.
//
// The list of guides, their page counts and their file sizes are read from the
// PDFs themselves, so the page can never claim a guide that isn't there or a
// length that is out of date. Run this after tools/build-guides.sh.
//
//   node tools/build-downloads-page.js
// =============================================================================
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PAGE = path.join(ROOT, 'request-a-guide.html');
const MANIFEST = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools/guide-manifest.json'), 'utf8'));

const NZ = new Set(['moving-to-new-zealand', 'auckland', 'wellington', 'christchurch', 'waikato',
  'bay-of-plenty', 'northland', 'hawkes-bay', 'palmerston-north', 'nelson-tasman',
  'dunedin', 'central-otago', 'southland', 'gisborne'].map(s => s.includes('moving') ? s : s + '-relocation-guide'));

// Page counts are read from the file with qpdf rather than by pattern-matching
// the bytes: the build compresses object streams, so the page tree is not
// plain text by the time we get here, and a silent zero would print on the page.
const { execFileSync } = require('child_process');

function pdfFacts(slug) {
  const p = path.join(ROOT, 'assets/downloads', slug + '.pdf');
  if (!fs.existsSync(p)) return null;
  const bytes = fs.statSync(p).size;
  const pages = parseInt(execFileSync('qpdf', ['--show-npages', p], { encoding: 'utf8' }).trim(), 10);
  if (!Number.isInteger(pages) || pages < 1) throw new Error(`${slug}: qpdf gave no page count`);
  const mb = bytes / 1048576;
  return { pages, size: mb < 1 ? `${Math.round(bytes / 1024)} KB` : `${mb.toFixed(1)} MB` };
}

function card(g) {
  const f = pdfFacts(g.slug);
  if (!f) throw new Error(`no PDF for ${g.slug} — run tools/build-guides.sh first`);
  const national = g.eyebrow.startsWith('The national');
  return `        <a class="dl${national ? ' dl-nat' : ''}" href="/assets/downloads/${g.slug}.pdf" download>`
    + `<span class="dl-t">${g.title}</span>`
    + (national ? `<span class="dl-n">The national guide</span>` : '')
    + `<span class="dl-m">PDF &middot; ${f.pages} pages &middot; ${f.size}</span></a>`;
}

const nz = MANIFEST.filter(g => NZ.has(g.slug));
const au = MANIFEST.filter(g => !NZ.has(g.slug));

const list = `<!-- GUIDE LIST · generated by tools/build-downloads-page.js — do not hand-edit -->
      <div class="dl-h">New Zealand</div>
      <div class="dl-grid">
${nz.map(card).join('\n')}
      </div>
      <div class="dl-h">Australia</div>
      <div class="dl-grid">
${au.map(card).join('\n')}
      </div>
<!-- /GUIDE LIST -->`;

const src = fs.readFileSync(PAGE, 'utf8');
const re = /<!-- GUIDE LIST[\s\S]*?<!-- \/GUIDE LIST -->/;
if (!re.test(src)) throw new Error('request-a-guide.html has no GUIDE LIST block to replace');
fs.writeFileSync(PAGE, src.replace(re, list));
console.log(`request-a-guide.html: ${nz.length} New Zealand + ${au.length} Australia guides listed`);
